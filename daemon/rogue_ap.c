/*
 * rogue_ap.c — Evil twin: a hostapd AP on a dedicated `__ap` vif.
 *
 * The daemon owns one radio. Monitor mode takes the whole phy, so the twin
 * cannot be a netifd/UCI network: bringing the wireless stack up would kill
 * the capture. Instead this module adds a second virtual interface to the
 * same phy (`iw phy phy0 interface add pwn4c-ap type __ap`), runs hostapd on
 * it with a generated /tmp config, and runs a second dnsmasq that serves
 * 192.168.66.0/24 on that interface only. The monitor vif keeps capturing on
 * the same channel, which is what makes the kick-and-join flow work.
 *
 * The two configuration files are produced by pure builders so the exact
 * hostapd/dnsmasq text is unit-tested. Nothing here interpolates an SSID or
 * passphrase into a shell command: the SSID goes into the config as `ssid2`
 * hex, and the passphrase is turned into a 64-hex PSK with util_wpa_psk_hex().
 *
 * The AP and the monitor share one phy. mac80211 allows the combination on
 * most drivers, but mt7603 is not guaranteed to; hostapd failing to come up
 * is reported as a clear error pointing at the log.
 */

#include "pwn4cd.h"

#include <errno.h>
#include <signal.h>
#include <stdarg.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <unistd.h>

#define ROGUE_CONF_BUF      1024u
#define ROGUE_REPORT_BUF    640u
#define ROGUE_ERR_BUF       192u
#define ROGUE_START_SETTLE  700   /* ms hostapd gets to bring the AP up     */
#define ROGUE_CLIENTS_TTL   2000  /* ms between `iw station dump` refreshes */

static char s_error[ROGUE_ERR_BUF];
static char s_report[ROGUE_REPORT_BUF];

/* ── Helpers ──────────────────────────────────────────────────────────────── */

static void rogue_set_error(const char *msg)
{
    (void)snprintf(s_error, sizeof(s_error), "%s", msg ? msg : "unknown error");
}

static void rogue_hex(const uint8_t *in, size_t len, char *out)
{
    static const char HEX[] = "0123456789abcdef";
    size_t i;

    for (i = 0; i < len; i++) {
        out[i * 2]     = HEX[(in[i] >> 4) & 0x0fu];
        out[i * 2 + 1] = HEX[in[i] & 0x0fu];
    }
    out[len * 2] = '\0';
}

static int rogue_write_file(const char *path, const char *content)
{
    FILE   *f;
    size_t  len;

    if (!path || !content) { return -1; }

    f = fopen(path, "w");
    if (!f) {
        util_log("rogue", "open %s: %s", path, strerror(errno));
        return -1;
    }
    len = strlen(content);
    if (fwrite(content, 1, len, f) != len) {
        util_log("rogue", "write %s: %s", path, strerror(errno));
        (void)fclose(f);
        return -1;
    }
    if (fclose(f) != 0) {
        util_log("rogue", "close %s: %s", path, strerror(errno));
        return -1;
    }
    return 0;
}

/* ── Pure configuration builders ──────────────────────────────────────────── */

/*
 * rogue_hostapd_conf — Render the hostapd configuration for one twin.
 *
 * `passphrase` may be NULL or "" for an open network. A WPA2-PSK twin gets
 * the derived 64-hex PSK instead of the passphrase, which removes every
 * quoting/escaping corner case from the config parser. The SSID is always
 * emitted as `ssid2` (hex), so any 1-32 byte name survives unchanged.
 *
 * Returns 0 on success, -1 on invalid input or a buffer that is too small.
 */
int rogue_hostapd_conf(const char *ssid, const char *passphrase, int channel,
                       bool hidden, char *out, size_t outsz)
{
    char   ssid_hex[ROGUE_SSID_MAX * 2 + 1];
    char   psk[65];
    size_t ssid_len;
    int    n;
    bool   wpa;

    if (!ssid || !out || outsz == 0) { return -1; }

    ssid_len = strlen(ssid);
    if (ssid_len < 1 || ssid_len > ROGUE_SSID_MAX) { return -1; }
    if (channel < CHAN_MIN || channel > CHAN_MAX)  { return -1; }

    wpa = (passphrase && passphrase[0] != '\0');
    if (wpa) {
        size_t pass_len = strlen(passphrase);
        if (pass_len < 8 || pass_len > 63) { return -1; }
        if (util_wpa_psk_hex(passphrase, ssid, psk) < 0) { return -1; }
    }

    rogue_hex((const uint8_t *)ssid, ssid_len, ssid_hex);

    n = snprintf(out, outsz,
        "# generated by pwn4cd — do not edit\n"
        "driver=nl80211\n"
        "interface=%s\n"
        "hw_mode=g\n"
        "channel=%d\n"
        "beacon_int=100\n"
        "auth_algs=1\n"
        "wmm_enabled=1\n"
        "ignore_broadcast_ssid=%d\n"
        "ssid2=%s\n",
        ROGUE_IFACE, channel, hidden ? 1 : 0, ssid_hex);
    if (n < 0 || (size_t)n >= outsz) { return -1; }

    if (wpa) {
        n = snprintf(out + n, outsz - (size_t)n,
            "wpa=2\n"
            "wpa_key_mgmt=WPA-PSK\n"
            "rsn_pairwise=CCMP\n"
            "wpa_psk=%s\n",
            psk);
    } else {
        n = snprintf(out + n, outsz - (size_t)n, "wpa=0\n");
    }
    if (n < 0 || (size_t)n >= outsz) { return -1; }

    return 0;
}

/*
 * rogue_dnsmasq_conf — DHCP only, on the twin's interface.
 *
 * `port=0` disables the DNS server outright: the image already runs one
 * dnsmasq for the drone's 192.168.4.0/24 LAN, and two resolvers cannot share
 * port 53. `bind-dynamic` keeps this instance off every other interface even
 * when netifd adds one later.
 */
int rogue_dnsmasq_conf(char *out, size_t outsz)
{
    int n;

    if (!out || outsz == 0) { return -1; }

    n = snprintf(out, outsz,
        "# generated by pwn4cd — do not edit\n"
        "port=0\n"
        "interface=%s\n"
        "bind-dynamic\n"
        "except-interface=lo\n"
        "dhcp-authoritative\n"
        "dhcp-range=%s.10,%s.200,255.255.255.0,12h\n"
        "dhcp-option=3,%s\n"
        "dhcp-option=6,%s\n"
        "log-facility=/tmp/pwn4c-dnsmasq.log\n",
        ROGUE_IFACE, ROGUE_NET_PREFIX, ROGUE_NET_PREFIX,
        ROGUE_IP, ROGUE_IP);
    if (n < 0 || (size_t)n >= outsz) { return -1; }

    return 0;
}

/* ── Process helpers ──────────────────────────────────────────────────────── */

static bool rogue_pid_alive(const char *pidfile)
{
    char buf[32];
    int  pid;

    if (util_read_file(pidfile, buf, sizeof(buf)) <= 0) { return false; }
    pid = atoi(buf);
    if (pid <= 0) { return false; }
    return kill((pid_t)pid, 0) == 0;
}

static void rogue_kill_pid(const char *pidfile)
{
    char buf[32];
    int  pid;

    if (util_read_file(pidfile, buf, sizeof(buf)) <= 0) { return; }
    pid = atoi(buf);
    if (pid <= 0) { return; }

    (void)kill((pid_t)pid, SIGTERM);
    util_sleep_ms(150);
    if (kill((pid_t)pid, 0) == 0) {
        (void)kill((pid_t)pid, SIGKILL);
    }
}

static void rogue_remove_pidfile(const char *pidfile)
{
    (void)unlink(pidfile);
}

/* Remove the vif and every artifact a previous run may have left behind. */
static void rogue_teardown_vif(void)
{
    char cmd[128];

    (void)snprintf(cmd, sizeof(cmd),
                   "ip addr flush dev %s 2>/dev/null", ROGUE_IFACE);
    (void)util_run_cmd_timeout_quiet(cmd, 2);

    (void)snprintf(cmd, sizeof(cmd),
                   "ip link set dev %s down 2>/dev/null", ROGUE_IFACE);
    (void)util_run_cmd_timeout_quiet(cmd, 2);

    (void)snprintf(cmd, sizeof(cmd),
                   "iw dev %s del 2>/dev/null", ROGUE_IFACE);
    (void)util_run_cmd_timeout_quiet(cmd, IW_TIMEOUT_SECS);
}

/* ── Start / stop ─────────────────────────────────────────────────────────── */

int rogue_start(daemon_t *d, const char *ssid, const char *bssid, int channel,
                const char *passphrase, bool hidden)
{
    char    hostapd_conf[ROGUE_CONF_BUF];
    char    dnsmasq_conf[ROGUE_CONF_BUF];
    char    cmd[256];
    char    mac_s[18];
    uint8_t mac[6];
    bool    wpa;
    bool    monitoring;

    if (!d) { return -2; }

    if (d->rogue.active) {
        rogue_set_error("a rogue AP is already running");
        return -2;
    }
    if (!ssid || strlen(ssid) < 1 || strlen(ssid) > ROGUE_SSID_MAX) {
        rogue_set_error("ssid must be 1-32 bytes");
        return -1;
    }
    if (!bssid || util_parse_mac(bssid, mac) < 0) {
        rogue_set_error("bssid is not a valid MAC address");
        return -1;
    }
    if (mac[0] & 0x01u) {
        rogue_set_error("bssid must be a unicast address");
        return -1;
    }
    if (channel < CHAN_MIN || channel > CHAN_MAX) {
        rogue_set_error("channel must be between 1 and 13");
        return -1;
    }
    wpa = (passphrase && passphrase[0] != '\0');
    if (wpa && (strlen(passphrase) < 8 || strlen(passphrase) > 63)) {
        rogue_set_error("passphrase must be 8-63 characters (or empty for an open AP)");
        return -1;
    }

    if (rogue_hostapd_conf(ssid, passphrase, channel, hidden,
                           hostapd_conf, sizeof(hostapd_conf)) < 0) {
        rogue_set_error("failed to render the hostapd configuration");
        return -1;
    }
    if (rogue_dnsmasq_conf(dnsmasq_conf, sizeof(dnsmasq_conf)) < 0) {
        rogue_set_error("failed to render the dnsmasq configuration");
        return -1;
    }

    monitoring = (d->state == STATE_MONITORING || d->state == STATE_INJECTING);

    /*
     * One radio, one channel. If a capture is already running on another
     * channel, hostapd would drag the whole phy with it and silently move the
     * monitor too. Refuse instead of desynchronising both.
     */
    if (monitoring && d->channel != channel) {
        (void)snprintf(s_error, sizeof(s_error),
            "monitor is on channel %d; switch it to %d before starting the twin",
            d->channel, channel);
        return -2;
    }

    if (d->mock_mode) {
        memset(&d->rogue, 0, sizeof(d->rogue));
        d->rogue.active         = true;
        d->rogue.wpa            = wpa;
        d->rogue.hidden         = hidden;
        d->rogue.channel        = channel;
        d->rogue.monitor_active = monitoring;
        d->rogue.hostapd        = true;
        d->rogue.dnsmasq        = true;
        d->rogue.start_ms       = util_monotonic_ms();
        (void)snprintf(d->rogue.ssid, sizeof(d->rogue.ssid), "%s", ssid);
        memcpy(d->rogue.bssid, mac, 6);
        util_log("rogue", "mock twin up: ssid=%s ch=%d wpa=%d",
                 ssid, channel, (int)wpa);
        return 0;
    }

    /* A crashed previous run may have left the vif (and hostapd) behind. */
    rogue_kill_pid(ROGUE_HOSTAPD_PID);
    rogue_kill_pid(ROGUE_DNSMASQ_PID);
    rogue_teardown_vif();

    (void)snprintf(cmd, sizeof(cmd),
                   "iw phy phy0 interface add %s type __ap", ROGUE_IFACE);
    if (util_run_cmd_timeout_quiet(cmd, IW_TIMEOUT_SECS) != 0) {
        (void)snprintf(cmd, sizeof(cmd),
                       "iw dev %s interface add %s type __ap",
                       d->wlan_iface, ROGUE_IFACE);
        if (util_run_cmd_timeout_quiet(cmd, IW_TIMEOUT_SECS) != 0) {
            rogue_set_error("failed to create the pwn4c-ap interface (iw)");
            return -2;
        }
    }

    util_mac_to_str(mac, mac_s, sizeof(mac_s));
    (void)snprintf(cmd, sizeof(cmd),
                   "ip link set dev %s address %s", ROGUE_IFACE, mac_s);
    if (util_run_cmd_timeout_quiet(cmd, 2) != 0) {
        rogue_set_error("failed to set the twin's BSSID");
        rogue_teardown_vif();
        return -2;
    }

    (void)snprintf(cmd, sizeof(cmd), "ip link set dev %s up", ROGUE_IFACE);
    if (util_run_cmd_timeout_quiet(cmd, 2) != 0) {
        rogue_set_error("failed to bring pwn4c-ap up");
        rogue_teardown_vif();
        return -2;
    }

    (void)snprintf(cmd, sizeof(cmd), "ip addr add %s/%s dev %s",
                   ROGUE_IP, ROGUE_NETMASK, ROGUE_IFACE);
    if (util_run_cmd_timeout_quiet(cmd, 2) != 0) {
        rogue_set_error("failed to assign " ROGUE_IP " to pwn4c-ap");
        rogue_teardown_vif();
        return -2;
    }

    if (rogue_write_file(ROGUE_HOSTAPD_CONF, hostapd_conf) < 0) {
        rogue_set_error("failed to write " ROGUE_HOSTAPD_CONF);
        rogue_teardown_vif();
        return -2;
    }
    if (rogue_write_file(ROGUE_DNSMASQ_CONF, dnsmasq_conf) < 0) {
        rogue_set_error("failed to write " ROGUE_DNSMASQ_CONF);
        rogue_teardown_vif();
        return -2;
    }

    (void)snprintf(cmd, sizeof(cmd),
                   "hostapd -B -P %s -f %s %s",
                   ROGUE_HOSTAPD_PID, ROGUE_HOSTAPD_LOG, ROGUE_HOSTAPD_CONF);
    if (util_run_cmd_timeout(cmd, 10) != 0) {
        rogue_set_error("hostapd refused the configuration (see " ROGUE_HOSTAPD_LOG ")");
        rogue_teardown_vif();
        return -2;
    }

    /* `-B` forks before the interface is configured, so a setup failure lands
     * after the command returned. Give it a moment, then check the pid. */
    util_sleep_ms(ROGUE_START_SETTLE);
    if (!rogue_pid_alive(ROGUE_HOSTAPD_PID)) {
        rogue_set_error("hostapd exited during setup — this radio may not allow an "
                    "AP and a monitor interface at the same time (see "
                    ROGUE_HOSTAPD_LOG ")");
        rogue_teardown_vif();
        return -2;
    }

    memset(&d->rogue, 0, sizeof(d->rogue));
    d->rogue.active         = true;
    d->rogue.wpa            = wpa;
    d->rogue.hidden         = hidden;
    d->rogue.channel        = channel;
    d->rogue.monitor_active = monitoring;
    d->rogue.hostapd        = true;
    d->rogue.start_ms       = util_monotonic_ms();
    (void)snprintf(d->rogue.ssid, sizeof(d->rogue.ssid), "%s", ssid);
    memcpy(d->rogue.bssid, mac, 6);

    /* DHCP is a convenience, not a prerequisite: a client that joins still
     * produces the 4-way handshake even if dnsmasq cannot start. */
    (void)snprintf(cmd, sizeof(cmd),
                   "dnsmasq --conf-file=%s --pid-file=%s",
                   ROGUE_DNSMASQ_CONF, ROGUE_DNSMASQ_PID);
    if (util_run_cmd_timeout(cmd, 5) != 0 || !rogue_pid_alive(ROGUE_DNSMASQ_PID)) {
        d->rogue.dnsmasq = false;
        util_log("rogue", "dnsmasq failed; the twin serves no DHCP");
    } else {
        d->rogue.dnsmasq = true;
    }

    util_log("rogue", "twin up: ssid=%s bssid=%s ch=%d wpa=%d monitor=%d",
             ssid, mac_s, channel, (int)wpa, (int)monitoring);
    return 0;
}

int rogue_stop(daemon_t *d)
{
    if (!d) { return -1; }

    if (d->mock_mode) {
        if (d->rogue.active) {
            util_log("rogue", "mock twin down");
        }
        memset(&d->rogue, 0, sizeof(d->rogue));
        return 0;
    }

    rogue_kill_pid(ROGUE_DNSMASQ_PID);
    rogue_kill_pid(ROGUE_HOSTAPD_PID);
    rogue_remove_pidfile(ROGUE_DNSMASQ_PID);
    rogue_remove_pidfile(ROGUE_HOSTAPD_PID);
    rogue_teardown_vif();

    if (d->rogue.active) {
        util_log("rogue", "twin down");
    }
    memset(&d->rogue, 0, sizeof(d->rogue));
    return 0;
}

/* ── Status ───────────────────────────────────────────────────────────────── */

static void rogue_refresh_clients(daemon_t *d)
{
    static char out[2048];
    int64_t     now = util_monotonic_ms();
    int         n = 0;
    const char *p;

    if (d->rogue.clients_ms != 0
        && now - d->rogue.clients_ms < ROGUE_CLIENTS_TTL) {
        return;
    }
    d->rogue.clients_ms = now;

    (void)util_run_cmd_capture("iw dev " ROGUE_IFACE " station dump 2>/dev/null",
                               out, sizeof(out), 1);

    for (p = out; (p = strstr(p, "Station ")) != NULL; p += 8) {
        n++;
    }
    d->rogue.clients = n;
}

const char *rogue_report(daemon_t *d)
{
    char    ssid_esc[ROGUE_SSID_MAX * 2 + 1];
    char    bssid_s[18];
    int64_t uptime_sec = 0;

    if (!d || !d->rogue.active) {
        (void)snprintf(s_report, sizeof(s_report), "{\"active\":false}");
        return s_report;
    }

    if (d->mock_mode) {
        d->rogue.clients = cl_tracked_count();
    } else {
        rogue_refresh_clients(d);
    }

    if (d->rogue.start_ms > 0) {
        uptime_sec = (util_monotonic_ms() - d->rogue.start_ms) / 1000;
        if (uptime_sec < 0) { uptime_sec = 0; }
    }

    util_json_escape(d->rogue.ssid, ssid_esc, sizeof(ssid_esc));
    util_mac_to_str(d->rogue.bssid, bssid_s, sizeof(bssid_s));

    (void)snprintf(s_report, sizeof(s_report),
        "{\"active\":true,\"ssid\":\"%s\",\"bssid\":\"%s\",\"channel\":%d,"
        "\"hidden\":%s,\"security\":\"%s\",\"interface\":\"%s\",\"ip\":\"%s\","
        "\"clients\":%d,\"uptime_sec\":%ld,\"hostapd\":%s,\"dnsmasq\":%s,"
        "\"monitor_active\":%s}",
        ssid_esc, bssid_s, d->rogue.channel,
        d->rogue.hidden ? "true" : "false",
        d->rogue.wpa ? "wpa2-psk" : "open",
        ROGUE_IFACE, ROGUE_IP,
        d->rogue.clients, (long)uptime_sec,
        d->rogue.hostapd ? "true" : "false",
        d->rogue.dnsmasq ? "true" : "false",
        d->rogue.monitor_active ? "true" : "false");

    return s_report;
}

const char *rogue_error(void)
{
    return s_error[0] ? s_error : "rogue AP operation failed";
}
